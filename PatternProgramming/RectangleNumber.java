package PatternProgramming;

public class RectangleNumber {
    public static void main(String[] args) {
        for(int i=1;i<=5;i++)
        {
            for(int j=1;j<=5;j++)
            {
                System.out.print(j+" ");  // We can change i and j in this field.
            }
            System.out.println();
        }
    }
}
